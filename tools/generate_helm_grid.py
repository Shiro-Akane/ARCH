"""Emit the frozen Linux extended-precision Helm grid as portable binary64 data.
The two axes preserve the existing 64-significand-bit long-double arithmetic
and final binary64 rounding. This is a developer tool; no runtime dependency.
"""
from decimal import Decimal, ROUND_HALF_EVEN, localcontext
from pathlib import Path
import argparse, hashlib, math, struct

AXES = (("density", -12, 15, 541), ("temperature", 3, 13, 201))

def extended(value):
    """Round one original arithmetic result to the x87 64-bit significand."""
    if not value:
        return value
    exponent = math.frexp(float(abs(value)))[1] - 1
    quantum = Decimal(2) ** (exponent - 63)
    return (value / quantum).to_integral_value(rounding=ROUND_HALF_EVEN) * quantum

def emit():
    axes = []
    with localcontext() as context:
        context.prec = 110
        context.rounding = ROUND_HALF_EVEN
        for name, low, high, count in AXES:
            steps = Decimal(count - 1) / (high - low)
            values = [float(extended(Decimal(10) ** extended(Decimal(low) + extended(Decimal(i) / steps))))
                      for i in range(count)]
            axes.append((name, low, high, values))
    digest = hashlib.sha256(b"".join(struct.pack(">d", value)
                                    for _, _, _, values in axes for value in values)).hexdigest()
    lines = ["/** Generated by tools/generate_helm_grid.py; do not edit the data.",
             " * Preserves the frozen Linux long-double grid, including its intermediate rounding.",
             " * IEEE binary64 values, network byte order SHA256: " + digest,
             " */", "#pragma once", "#include <array>", "", "namespace helm_eos::grid {",
             "inline constexpr double steps_per_decade = 20.0;"]
    for name, low, high, values in axes:
        lines += [f"inline constexpr double {name}_log_min = {low}.0;",
                  f"inline constexpr double {name}_log_max = {high}.0;",
                  f"inline constexpr std::array<double, {len(values)}> {name}_nodes = {{"]
        for index in range(0, len(values), 4):
            lines.append("    " + ", ".join(value.hex() for value in values[index:index+4]) + ",")
        lines += ["};", ""]
    return "\n".join(lines + ["} // namespace helm_eos::grid", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "src/physics/eos/sources/HelmGridNodes.h")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = emit()
    if args.check:
        if args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit("Helm grid differs from its generator")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected, encoding="utf-8")
